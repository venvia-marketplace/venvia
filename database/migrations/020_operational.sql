-- VenVia 0.2.0 bootstrap gestionale: additiva, non distruttiva.
CREATE TABLE IF NOT EXISTS vv_operational_users (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(64) NOT NULL UNIQUE,
 email VARCHAR(254) NOT NULL,
 role VARCHAR(48) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 totp_encrypted TEXT NOT NULL,
 recovery_hash VARCHAR(255) NOT NULL,
 credential_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 last_login_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS vv_operational_invites (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 token_hash CHAR(64) NOT NULL UNIQUE,
 role VARCHAR(48) NOT NULL,
 created_by VARCHAR(64) NOT NULL,
 expires_at DATETIME NOT NULL,
 consumed_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS vv_operational_login_attempt (
 ip_hash CHAR(64) NOT NULL PRIMARY KEY,
 attempts INT UNSIGNED NOT NULL,
 last_attempt DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS vv_plugin_registry (
 plugin_id VARCHAR(100) NOT NULL PRIMARY KEY,
 version VARCHAR(40) NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'disabled',
 installed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS vv_core_migrations (
 migration_id VARCHAR(80) NOT NULL PRIMARY KEY,
 checksum_sha256 CHAR(64) NOT NULL,
 applied_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
